#!/usr/bin/env python3
"""Write database/schema.sql – the PostgreSQL DDL generated from the SQLAlchemy models.
The application creates the same schema automatically with `python -m app.seed`."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app import models  # noqa: E402,F401
from app.database import Base  # noqa: E402
from sqlalchemy.dialects import postgresql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

out = ["-- VISTA database schema (PostgreSQL). Generated by scripts/export_schema.py – do not edit by hand.",
       "-- Apply with:  psql \"$DATABASE_URL\" -f database/schema.sql   (or run: cd backend && python -m app.seed)", ""]
for table in Base.metadata.sorted_tables:
    out.append(str(CreateTable(table).compile(dialect=postgresql.dialect())).strip() + ";")
    for idx in sorted(table.indexes, key=lambda i: i.name):
        out.append(str(CreateIndex(idx).compile(dialect=postgresql.dialect())).strip() + ";")
    out.append("")
(ROOT / "database").mkdir(exist_ok=True)
(ROOT / "database" / "schema.sql").write_text("\n".join(out))
print(f"Wrote database/schema.sql ({len(Base.metadata.sorted_tables)} tables)")
